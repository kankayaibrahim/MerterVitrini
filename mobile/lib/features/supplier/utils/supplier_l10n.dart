  static String t(String lang, String key) {
    final code = AppStrings.normalizeCode(lang);
    final localized = _byLang[code]?[key];
    if (localized != null) return localized;
    final en = _byLang['en']?[key];
    if (en != null) return en;
    return AppStrings.t(code, key);
  }

  static String upper(String lang, String key) {
    final val = t(lang, key);
    return AppStrings.normalizeCode(lang) == 'ar' ? val : val.toUpperCase();
  }

