export function getCategoryTrail(tree: Category[] | undefined | null, targetIdOrSlug: string, trail: Category[] = []): Category[] | null {
  if (!tree) return null;
  for (const cat of tree) {
    if (cat.id === targetIdOrSlug || cat.slug === targetIdOrSlug) {
      return [...trail, cat];
    }
    if (cat.children && cat.children.length > 0) {
      const found = getCategoryTrail(cat.children, targetIdOrSlug, [...trail, cat]);
      if (found) return found;
    }
  }
  return null;
}

export function getCategoryUrl(tree: Category[] | undefined | null, target: Category | string, lang: string): string {
  if (!target) return "/";
  const targetIdOrSlug = typeof target === "string" ? target : (target.slug || target.id);
  const prefix = getCategoryPrefix(lang);
  if (!tree) {
    return `/${prefix}/${targetIdOrSlug}/`;
  }
  const trail = getCategoryTrail(tree, targetIdOrSlug);
  if (!trail || trail.length === 0) {
    return `/${prefix}/${targetIdOrSlug}/`;
  }
  const slugPath = trail.map(cat => cat.slug || cat.id).join("/");
  return `/${prefix}/${slugPath}/`;
}

export function translateColor(color: string | undefined | null, lang: string): string {
  if (!color) return "";
  const parts = color.trim().split(/\s+/);
  const translatedParts = parts.map(part => {
    return t(part, lang);
  });
  return translatedParts.join(" ");
}
