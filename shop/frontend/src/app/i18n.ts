export function getProductDescription(product: Product, lang: string): string {
  const allowedLangs = ["en", "pl", "ar", "ru", "de", "bg", "fr"];
  const safeLang = allowedLangs.includes(lang) ? lang : "";
  let desc = "";
  
  if (safeLang && product.translations && safeLang !== "__proto__" && safeLang !== "constructor") {
    const trans = product.translations;
    if (Object.prototype.hasOwnProperty.call(trans, safeLang)) {
      const transObj = trans[safeLang];
      if (transObj && Object.prototype.hasOwnProperty.call(transObj, "description")) {
        desc = transObj.description || product.description || "";
      }
    }
  }
  if (!desc) {
    desc = product.description || product.short_description || "";
  }
  // Post-process description to translate any residual Turkish technical keywords securely
  if (lang !== "tr" && desc) {
    let replacements: DescriptionReplacement[] | undefined = undefined;
    switch (lang) {
      case "en":
        replacements = descCleanupRegexMap.en;
        break;
      case "pl":
        replacements = descCleanupRegexMap.pl;
        break;
      case "ru":
        replacements = descCleanupRegexMap.ru;
        break;
      case "ar":
        replacements = descCleanupRegexMap.ar;
        break;
      case "de":
        replacements = descCleanupRegexMap.de;
        break;
      case "bg":
        replacements = descCleanupRegexMap.bg;
        break;
      case "fr":
        replacements = descCleanupRegexMap.fr;
        break;
    }

    if (replacements) {
      for (const r of replacements) {
        desc = desc.replace(r.regex, r.val);
      }
    }
  }
  return desc;
}

