// Get correct translated title / description for dynamic product
window.getProductTitle = function(product) {
    if (window.currentLang !== 'tr' && product.translations) {
        const allowedLangs = ['en', 'pl', 'ar', 'ru', 'de'];
        const lang = allowedLangs.includes(window.currentLang) ? window.currentLang : '';
        if (lang && product.translations[lang] && Object.prototype.hasOwnProperty.call(product.translations[lang], 'title')) {
            return product.translations[lang].title || product.title;
        }
    }
    return product.title;
};

window.getProductDescription = function(product) {
    if (window.currentLang !== 'tr' && product.translations) {
        const allowedLangs = ['en', 'pl', 'ar', 'ru', 'de'];
        const lang = allowedLangs.includes(window.currentLang) ? window.currentLang : '';
        if (lang && product.translations[lang] && Object.prototype.hasOwnProperty.call(product.translations[lang], 'description')) {
            return product.translations[lang].description || product.description;
        }
    }
    return product.description || product.short_description || "";
};
