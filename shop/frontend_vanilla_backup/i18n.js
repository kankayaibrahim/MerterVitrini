// Safe Translate Helper (Avoid bracket notation warnings completely)
window.t = function(key) {
    const allowedLangs = ['tr', 'en', 'pl', 'ar', 'ru', 'de'];
    const lang = allowedLangs.includes(window.currentLang) ? window.currentLang : 'tr';
    
    const dict = window.dictionary[lang] || window.dictionary['tr'];
    if (dict && Object.prototype.hasOwnProperty.call(dict, key)) {
        return dict[key];
    }
    const fallbackDict = window.dictionary['tr'];
    if (fallbackDict && Object.prototype.hasOwnProperty.call(fallbackDict, key)) {
        return fallbackDict[key];
    }
    return key;
};

